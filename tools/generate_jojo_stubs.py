#!/usr/bin/env python3
"""Generate the JoJo EoH import tables from the public shadPS4 log.

Two generated files:
  src/jojo_import_names.inc  NID#library -> symbol, for NIDs the GOW3-derived
                             import_names.inc does not know.
  src/jojo_stubs.inc         symbol -> existing generic handler in
                             runtime_services.c. Only symbols without a real
                             implementation are listed here.

The log is a compatibility report from a machine that already runs the game;
it is evidence of which imports the executable resolves, not proof that the
stubs below are semantically complete.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

INC_RE = re.compile(r'\{"([^"#]+)#([^"]+)","([^"]+)"\}')
LOG_RE = re.compile(
    r'Stub resolved\s+(\S+)\s+as\s+(\S+)\s+\(lib:\s*([^,]+),\s*mod:\s*([^)]+)\)'
)
NATIVE_LIBS = {'libc', 'libSceLibcInternal', 'libSceFios2'}
RTC_REAL = {
    'sceRtcGetCurrentTick',
    'sceRtcGetWin32FileTime',
    'sceRtcSetWin32FileTime',
    'sceRtcParseDateTime',
    'sceRtcParseRFC3339',
}


def handler_for(lib: str, name: str) -> str | None:
    if lib == 'libSceRtc':
        return name if name in RTC_REAL else 'jojo_unsupported'
    if lib in {'libSceJpegDec', 'libSceJpegEnc', 'libScePngEnc'}:
        return 'jojo_unsupported'
    if lib in {'libkernel', 'libSceVideoRecording'}:
        return 'ok_void'
    if lib == 'libSceVoiceQoS':
        if name.startswith(('sceVoiceQoSInit', 'sceVoiceQoSEnd', 'sceVoiceQoSDelete',
                            'sceVoiceQoSDisconnect', 'sceVoiceQoSSet')):
            return 'ok_void'
        return 'np_signed_out'
    if 'Dialog' in lib:
        return 'ok_void' if name.endswith(('Initialize', 'Terminate', 'Close')) else 'np_signed_out'
    if lib.startswith('libSceNp'):
        quiet = ('Initialize', 'Terminate', 'Delete', 'Abort', 'Stop', 'Shutdown',
                 'Destroy', 'Set', 'Register', 'Unregister')
        return 'ok_void' if any(token in name for token in quiet) else 'np_signed_out'
    return 'jojo_unsupported'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('log', type=Path)
    parser.add_argument('--inc', type=Path, default=Path('src/import_names.inc'))
    parser.add_argument('--names-out', type=Path, default=Path('src/jojo_import_names.inc'))
    parser.add_argument('--stubs-out', type=Path, default=Path('src/jojo_stubs.inc'))
    args = parser.parse_args()

    known = {(nid, lib) for nid, lib, _ in INC_RE.findall(
        args.inc.read_text(encoding='utf-8', errors='replace'))}
    rows = LOG_RE.findall(args.log.read_text(encoding='utf-8', errors='replace'))
    unique = {}
    for nid, name, lib, _mod in rows:
        unique[(nid, lib.strip())] = name

    missing = sorted(
        ((nid, lib, name) for (nid, lib), name in unique.items()
         if (nid, lib) not in known and lib not in NATIVE_LIBS),
        key=lambda x: (x[1], x[2]),
    )
    names_lines = [
        '/* Generated by tools/generate_jojo_stubs.py from a public CUSA04909 log. */',
    ]
    stub_lines = [
        '/* Generated by tools/generate_jojo_stubs.py. Included in runtime_services.c. */',
    ]
    seen_symbols = set()
    for nid, lib, name in missing:
        names_lines.append(f'{{"{nid}#{lib}","{name}"}},')
        handler = handler_for(lib, name)
        if handler and handler != name and name not in seen_symbols:
            stub_lines.append(f'{{"{name}",{handler}}},')
            seen_symbols.add(name)

    args.names_out.write_text('\n'.join(names_lines) + '\n', encoding='utf-8')
    args.stubs_out.write_text('\n'.join(stub_lines) + '\n', encoding='utf-8')
    print(f'wrote {args.names_out} and {args.stubs_out}: '
          f'{len(missing)} NIDs, {len(seen_symbols)} stub entries')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
